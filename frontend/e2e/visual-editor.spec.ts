test('campo numérico recusado explica o erro e preserva a configuração anterior',async({page})=>{
  await mockApi(page,{exists:true})
  await page.goto('/#/workflows/'+ids.workflow)
  await page.getByRole('combobox',{name:'Tipo da nova etapa',exact:true}).selectOption('delay')
  await page.getByRole('button',{name:'Adicionar etapa',exact:true}).click()
  const seconds=page.getByLabel('Duração em segundos',{exact:true})
  await seconds.fill('abc')
  await expect(seconds).toHaveAttribute('aria-invalid','true')
  await expect(page.getByText('Digite um número, como 100 ou 2,5. O valor anterior continua salvo no rascunho.',{exact:true})).toBeVisible()
  await seconds.fill('0')
  await expect(page.getByText('Use um valor maior que 0 e de até 86.400 segundos (24 horas).',{exact:true})).toBeVisible()
  await seconds.fill('2,5')
  await expect(seconds).not.toHaveAttribute('aria-invalid','true')
  await page.getByRole('button',{name:'JSON',exact:true}).click()
  await expect(page.getByLabel('Configuração JSON da etapa 3',{exact:true})).toHaveValue(/"durationTicks": 25000000/)
})
